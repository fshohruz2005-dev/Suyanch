fun getString(key: StringKey, lang: AppLanguage): String {
  return when (lang) {
    AppLanguage.UZBEK -> uzbekStrings[key] ?: key.name
    AppLanguage.RUSSIAN -> russianStrings[key] ?: key.name
  }
}

@Composable
fun appString(key: StringKey): String {
  val lang = currentLanguage()
  return getString(key, lang)
}
